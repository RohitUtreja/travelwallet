const { launch, login, axe, shot, check, summary, BASE, ids, sql, press, toast } = require('./lib')
;(async () => {
  const { browser, page } = await launch()
  await login(page)
  const FAM = ids.FAM
  // ── A. add via keypad ──
  await page.goto(`${BASE}/groups/${FAM}/add`)
  await page.waitForSelector('text=Add expense')
  await press(page, '1250.50')
  check('amount display formatted', (await page.getByRole('group', { name: 'Amount' }).innerText()).includes('1,250.5'))
  await page.getByRole('button', { name: 'All' }).click()
  await axe(page, 'category sheet')
  await page.getByRole('dialog').getByText('Fitness', { exact: true }).click()
  await page.getByPlaceholder('Add a note (optional)').fill('Gym membership')
  await page.waitForTimeout(400); await shot(page, '05-add-expense'); await axe(page, 'add expense')
  await page.getByRole('button', { name: 'Save expense' }).click()
  check('toast: Expense added', await toast(page, /Expense added/))
  await page.waitForURL(`**/groups/${FAM}`)
  check('DB row saved with right category/amount', sql(`select amount||'/'||category from expenses where description='Gym membership'`) === '1250.50/fitness')
  check('recent category remembered', await page.evaluate((f) => JSON.parse(localStorage.getItem(`fw:recent:${f}`))[0], FAM) === 'fitness')
  await page.waitForSelector('text=₹64,280.50')
  check('overview total updated live', true)
  // ── C. edit ──
  await page.getByRole('tab', { name: 'Expenses' }).click()
  await page.getByRole('link', { name: /Edit Gym membership/ }).click()
  await page.waitForSelector('text=Edit expense')
  check('edit prefilled amount', await page.getByRole('group', { name: 'Amount' }).filter({ hasText: '1,250.5' }).waitFor({ timeout: 5000 }).then(() => true, () => false))
  await page.getByRole('button', { name: 'Delete', exact: true }).click(); await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Save changes' }).click()
  await page.waitForURL(`**/groups/${FAM}`)
  check('edited (backspace) saved as 1250.00', sql(`select amount from expenses where description='Gym membership'`) === '1250.00')
  // ── D. delete + undo ──
  await page.getByRole('tab', { name: 'Expenses' }).click()
  await page.getByRole('link', { name: /Edit Gym membership/ }).click()
  await page.getByRole('button', { name: 'More details' }).click()
  await page.getByRole('button', { name: 'Delete expense' }).click()
  await axe(page, 'confirm delete sheet')
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click()
  await page.waitForURL(`**/groups/${FAM}`)
  check('deleted in DB', sql(`select count(*) from expenses where description='Gym membership'`) === '0')
  await shot(page, '06-undo-toast')
  await page.getByRole('button', { name: 'Undo' }).click()
  check('toast: Restored', await toast(page, /Restored/))
  check('undo restored the row', sql(`select count(*) from expenses where description='Gym membership'`) === '1')
  // ── E. repeat ──
  await page.goto(`${BASE}/groups/${FAM}/add`)
  await press(page, '999')
  await page.getByRole('button', { name: 'More details' }).click()
  await page.getByText('Repeat this expense').click()
  await page.getByPlaceholder('Add a note (optional)').fill('Netflix')
  await page.getByRole('button', { name: 'Save expense' }).click()
  check('toast: repeats', await toast(page, /repeats every month/))
  await page.waitForURL(`**/groups/${FAM}`)
  check('recurring rule created', sql(`select count(*) from recurring_expenses where description='Netflix' and amount=999`) === '1')
  check('first occurrence generated immediately', sql(`select count(*) from expenses where amount=999`) === '1')
  // ── F. manage + budgets ──
  await page.getByRole('tab', { name: 'Manage' }).click()
  await page.waitForSelector('text=Members · 3')
  await shot(page, '07-manage', true); await axe(page, 'manage')
  await page.getByRole('button', { name: 'Edit monthly budgets' }).click()
  await page.getByLabel('Fitness monthly budget').fill('1000')
  await axe(page, 'budget sheet')
  await page.getByRole('button', { name: 'Save budgets' }).click()
  check('toast: Budgets saved', await toast(page, /Budgets saved/))
  check('budget row in DB', sql(`select monthly_limit from budgets where category='fitness'`) === '1000.00')
  await page.getByRole('tab', { name: 'Overview' }).click()
  await page.waitForSelector('text=/Fitness budget exceeded by/', { timeout: 8000 }).then(() => check('insight: fitness over budget', true), () => check('insight: fitness over budget', false))
  // ── L. quick add ──
  await page.goto(`${BASE}/groups`); await page.getByRole('link', { name: 'Add expense' }).click()
  await page.waitForURL(`**/groups/${FAM}/add`, { timeout: 8000 }).then(() => check('quick-add jumps to last wallet', true), () => check('quick-add jumps to last wallet', false))
  const ok = summary(); await browser.close(); process.exit(ok ? 0 : 1)
})().catch((e) => { console.error('E2E CRASH', e.message.split('\n').slice(0, 6).join('\n')); process.exit(2) })
