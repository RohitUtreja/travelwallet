const { launch, login, axe, shot, check, summary, BASE } = require('./lib')
const fs = require('fs')
;(async () => {
  const { browser, page } = await launch()
  // ── login ──
  await page.goto(BASE + '/login'); await page.waitForSelector('text=Sign in')
  await shot(page, '01-login'); await axe(page, 'login')
  await page.getByLabel('Email').fill('rohit@family.test'); await page.getByLabel('Password', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: 'Sign in' }).click()
  check('wrong password shows error', await page.getByRole('alert').filter({ hasText: 'Incorrect email or password' }).waitFor({ timeout: 5000 }).then(() => true, () => false))
  await page.getByLabel('Password', { exact: true }).fill('pw'); await page.getByRole('button', { name: 'Sign in' }).click()
  await page.waitForURL('**/groups')
  // ── wallets ──
  await page.waitForSelector('text=Utreja Household')
  check('personal wallet created + legacy rows migrated', await page.locator('a', { hasText: 'Personal' }).first().innerText().then((t) => /Personal/.test(t)))
  check('three wallets listed', (await page.locator('main a[href^="/groups/"]').count()) >= 3)
  check('split balance shown', await page.getByText('You’re owed').isVisible())
  await shot(page, '02-wallets'); await axe(page, 'wallets')
  // ── overview ──
  await page.locator('a', { hasText: 'Utreja Household' }).click()
  await page.waitForSelector('text=Spent in October 2026')
  const hero = await page.locator('section', { hasText: 'Spent in' }).first().innerText()
  check('hero total = ₹63,030.00 (incl. generated rent+SIP)', hero.includes('₹63,030.00'), hero)
  check('recurring materialised: 7 expenses this month', /7 expenses/.test(hero), hero)
  const ins = await page.locator('[aria-labelledby=ins]').innerText().catch(() => '')
  check('insight: overall budget 84% used', /Overall budget is 84% used/.test(ins), ins)
  check('budget progress bars exposed as progressbar', (await page.getByRole('progressbar').count()) >= 4)
  await page.waitForTimeout(900)
  await shot(page, '03-overview'); await shot(page, '03b-overview-full', true)
  await axe(page, 'overview')
  // ── expenses tab ──
  await page.getByRole('tab', { name: 'Expenses' }).click()
  await page.waitForSelector('text=Electricity bill')
  check('7 rows', (await page.locator('a[href*="/expense/"]').count()) === 7)
  await page.getByLabel('Search expenses').fill('petrol')
  check('search narrows to 1', (await page.locator('a[href*="/expense/"]').count()) === 1)
  await page.getByLabel('Search expenses').fill('')
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: /Export this month/ }).click()])
  const csv = fs.readFileSync(await dl.path(), 'utf8')
  check('CSV export: BOM + header + 7 rows', csv.startsWith('﻿Date,Description,Category,Spent by,Amount (INR)') && csv.trim().split('\r\n').length === 8, csv.slice(0, 200))
  check('CSV contains rent row', /House rent,Rent,Rohit,35000\.00/.test(csv))
  await shot(page, '04-expenses'); await axe(page, 'expenses')
  // previous month nav
  await page.getByRole('button', { name: 'Previous month' }).click()
  await page.waitForSelector('text=September 2026')
  await page.waitForFunction(() => document.querySelectorAll('a[href*="/expense/"]').length > 7, null, { timeout: 8000 }).catch(() => {})
  check('previous month has more rows', (await page.locator('a[href*="/expense/"]').count()) > 7)
  await page.getByRole('button', { name: 'Next month' }).click()
  const ok = summary(); await browser.close(); process.exit(ok ? 0 : 1)
})().catch((e) => { console.error('E2E CRASH', e.message); process.exit(2) })
